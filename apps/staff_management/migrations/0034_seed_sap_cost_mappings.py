def seed(apps, schema_editor):
    Centre = apps.get_model("staff_management", "SapCostCentre")
    Subsidiary = apps.get_model("staff_management", "SapSubsidiary")
    Exclusion = apps.get_model("staff_management", "SapCostExclusion")

    if Centre.objects.exists():
        print("\n  SAP cost mappings: already present - left alone.")
        return

    # bulk_create, not the model's save(), so is_branch is set explicitly here
    # rather than relying on a save() the historical model does not have.
    Centre.objects.bulk_create([Centre(**row) for row in CENTRES])
    Subsidiary.objects.bulk_create(
        [Subsidiary(**row) for row in SUBSIDIARIES])
    Exclusion.objects.bulk_create(
        [Exclusion(gl=gl, reason=reason) for gl, reason in EXCLUSIONS])

    branches = sum(1 for row in CENTRES if row["is_branch"])
    held = sum(1 for row in CENTRES if not row["is_reportable"])
    print(f"\n  SAP cost mappings: {len(CENTRES)} cost centres "
          f"({branches} branches, {held} not reportable), "
          f"{len(SUBSIDIARIES)} subsidiaries, "
          f"{len(EXCLUSIONS)} GL exclusions.")


def unseed(apps, schema_editor):
    """Nothing to undo: removing the mapping would take out corrections made
    through the screen since, and leave every posting unmapped."""


